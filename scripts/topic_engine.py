# ---------------------------------------------------
# LOAD USED TOPICS
# ---------------------------------------------------

def load_used_topics():

    if not os.path.exists(USED_TOPICS_FILE):
        return []

    try:

        with open(
            USED_TOPICS_FILE,
            "r",
            encoding="utf-8"
        ) as f:

            return json.load(f)

    except:
        return []

# ---------------------------------------------------
# SAVE USED TOPIC
# ---------------------------------------------------

def save_used_topic(topic):

    used = load_used_topics()

    used.append(topic)

    # keep last 300
    used = used[-300:]

    with open(
        USED_TOPICS_FILE,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            used,
            f,
            ensure_ascii=False,
            indent=2
        )

# ---------------------------------------------------
# GET TOPIC
# ---------------------------------------------------

def get_topic():

    today = datetime.today().strftime("%A")

    if today not in DAY_TOPICS:
        today = "Monday"

    topics = DAY_TOPICS[today]

    used = load_used_topics()

    # fresh topics first
    fresh = [

        t for t in topics
        if t not in used
    ]

    if not fresh:
        fresh = topics

    topic = random.choice(fresh)

    save_used_topic(topic)

    return topic

