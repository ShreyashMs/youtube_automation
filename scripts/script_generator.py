def generate_script():

    topic = random.choice(TOPICS)

    print(f"\nGenerating topic: {topic}")

    prompt = build_prompt(topic)

    try:

        response = requests.post(

            OLLAMA_URL,

            json={

                "model": MODEL_NAME,

                "prompt": prompt,

                "stream": False,

                "options": {

                    "temperature": 0.85,
                    "top_p": 0.9,
                    "repeat_penalty": 1.15,
                    "num_predict": 320,
                }
            },

            timeout=180
        )

        data = response.json()

        raw_script = data.get(
            "response",
            ""
        ).strip()

        script = clean_script(raw_script)

        if not validate_script(script):

            print("\nInvalid script. Retrying...\n")

            time.sleep(2)

            return generate_script()

        with open(
            SCRIPT_FILE,
            "w",
            encoding="utf-8"
        ) as f:

            f.write(script)

        return script

    except Exception as e:

        print(e)

        time.sleep(3)

        return generate_script()

