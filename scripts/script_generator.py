def load_used_topics():

    if not os.path.exists(USED_TOPICS_FILE):
        return []

    try:

        with open(
            USED_TOPICS_FILE,
            "r",
            encoding="utf-8"
        ) as f:

            return json.load(f)

    except:

        return []


def save_used_topic(topic):

    used_topics = load_used_topics()

    if topic not in used_topics:

        used_topics.append(topic)

        with open(
            USED_TOPICS_FILE,
            "w",
            encoding="utf-8"
        ) as f:

            json.dump(
                used_topics,
                f,
                ensure_ascii=False,
                indent=2
            )


def get_unused_topic():

    used_topics = load_used_topics()

    available_topics = [

        topic
        for topic in TOPICS
        if topic not in used_topics
    ]

    if not available_topics:

        raise Exception(
            "All topics have already been used."
        )

    return random.choice(
        available_topics
    )
    
def clean_script(script):

    script = script.replace("**", "")

    script = re.sub(
        r'\s+',
        ' ',
        script
    )

    return script.strip()

def validate_script(script):

    if len(script) < 250:
        return False

    hindi_chars = re.findall(
        r'[\u0900-\u097F]',
        script
    )

    if len(hindi_chars) < 80:
        return False

    return True

